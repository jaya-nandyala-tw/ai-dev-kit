import fs from "node:fs";
import path from "node:path";
import { repoPath } from "./paths";
import { buildDiff, hashContent } from "./diff";
import * as T from "./templates";
import type { DiffResult, FieldSchema } from "@/types";

export type ManagedFileDef = {
  key: string;
  label: string;
  relPaths: string[];
  /** Personal/local files (e.g. .env) never get the "already customized" three-way-diff
   * treatment — there's no meaningful "shipped baseline" to compare a dev's own .env against. */
  personal?: boolean;
  fields: FieldSchema[];
  baseline: (relPath: string) => string;
  parseCurrentValues: () => Record<string, unknown>;
  buildProposed: (values: Record<string, unknown>) => Record<string, string>;
};

function readIfExists(relPath: string): string | null {
  const abs = repoPath(relPath);
  return fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
}

// ── CODEOWNERS ──────────────────────────────────────────────────────────────

type OwnerRow = { pattern: string; owners: string };

function parseCodeowners(content: string): OwnerRow[] {
  return content
    .split("\n")
    .filter((line) => line.trim() && !line.trim().startsWith("#"))
    .map((line) => {
      const [pattern, ...rest] = line.trim().split(/\s+/);
      return { pattern: pattern ?? "", owners: rest.join(" ") };
    })
    .filter((row) => row.pattern);
}

const codeowners: ManagedFileDef = {
  key: "codeowners",
  label: "CODEOWNERS",
  relPaths: ["CODEOWNERS"],
  fields: [
    {
      name: "rows",
      label: "Path → owner rules (evaluated in order, last match wins)",
      type: "table",
      columns: [
        { name: "pattern", label: "Path glob", placeholder: "/scripts/" },
        { name: "owners", label: "Owner(s)", placeholder: "@your-org/platform-maintainers" },
      ],
    },
  ],
  baseline: () => T.CODEOWNERS_BASELINE,
  parseCurrentValues: () => {
    const current = readIfExists("CODEOWNERS") ?? "";
    return { rows: parseCodeowners(current) };
  },
  buildProposed: (values) => {
    const rows = (values.rows as OwnerRow[] | undefined) ?? [];
    const header = [
      "# CODEOWNERS — generated by onboarding-ui. Rules are evaluated in order; the last",
      "# matching rule wins.",
      "",
    ].join("\n");
    const body = rows
      .filter((r) => r.pattern?.trim())
      .map((r) => `${r.pattern.padEnd(28)} ${r.owners}`.trimEnd())
      .join("\n");
    return { CODEOWNERS: header + body + "\n" };
  },
};

// ── .pre-commit-config.yaml ─────────────────────────────────────────────────

const preCommitConfig: ManagedFileDef = {
  key: "pre-commit-config",
  label: "Pre-commit hook file globs",
  relPaths: [".pre-commit-config.yaml"],
  fields: [
    { name: "serviceDir", label: "Core service directory name (under codebase/)", type: "text", placeholder: "billing-service" },
    { name: "workersGlob", label: "Workers/lambdas glob (under codebase/)", type: "text", placeholder: "workers/.*" },
    { name: "iacPrefix", label: "IaC repo directory prefix (under codebase/) — leave blank if you have no IaC repo", type: "text", placeholder: "infra" },
  ],
  baseline: () => T.PRE_COMMIT_CONFIG_BASELINE,
  parseCurrentValues: () => {
    const current = readIfExists(".pre-commit-config.yaml") ?? T.PRE_COMMIT_CONFIG_BASELINE;
    const serviceDir = /files: \^codebase\/\(([^/]+)\/service\|/.exec(current)?.[1] ?? "";
    const workersGlob = /\/service\|([^)]+)\)\//.exec(current)?.[1] ?? "";
    const iacPrefix = /files: \^codebase\/([^\n]+)$/m.exec(current)?.[1] ?? "";
    return { serviceDir, workersGlob, iacPrefix };
  },
  buildProposed: (values) => {
    const serviceDir = String(values.serviceDir ?? "<service>").trim() || "<service>";
    const workersGlob = String(values.workersGlob ?? "<lambdas-or-workers>").trim() || "<lambdas-or-workers>";
    const iacPrefix = String(values.iacPrefix ?? "").trim();

    let proposed = T.PRE_COMMIT_CONFIG_BASELINE.replaceAll("<service>", serviceDir).replaceAll(
      "<lambdas-or-workers>",
      workersGlob,
    );

    if (iacPrefix) {
      proposed = proposed.replaceAll("<iac-repo-prefix>", iacPrefix);
    } else {
      // No IaC repo — drop the Terraform hook block entirely rather than leave an unmatched
      // placeholder glob in the file.
      proposed = proposed.replace(
        /\n {2}# ── Terraform[\s\S]*?(?=\n {2}# ── General hygiene)/,
        "\n",
      );
    }
    return { ".pre-commit-config.yaml": proposed };
  },
};

