const REGISTRY: Record<string, ManagedFileDef> = {
  codeowners,
  "pre-commit-config": preCommitConfig,
  "ci-workflow": ciWorkflow,
  "global-instructions": globalInstructions,
  "repos-json": reposJson,
  env: envFile,
  "env-template": envTemplateFile,
  "jira-board": jiraBoard,
};

export function getManagedFile(key: string): ManagedFileDef | undefined {
  return REGISTRY[key];
}

export function listManagedFileKeys(): string[] {
  return Object.keys(REGISTRY);
}

export function diffManagedFile(key: string, values: Record<string, unknown>): DiffResult[] {
  const def = getManagedFile(key);
  if (!def) throw new Error(`Unknown managed file "${key}"`);
  const proposedMap = def.buildProposed(values);
  return def.relPaths.map((relPath) => {
    const absolute = repoPath(relPath);
    const result = buildDiff({
      key: `${key}:${relPath}`,
      absolutePath: absolute,
      baseline: def.baseline(relPath),
      proposed: proposedMap[relPath] ?? "",
    });
    // A personal file (like .env) is never "customized" relative to a shipped baseline — every
    // dev's .env differs from every other dev's by design.
    if (def.personal) result.customized = false;
    return result;
  });
}

export function writeManagedFile(
  key: string,
  values: Record<string, unknown>,
  confirmedHashes: Record<string, string>,
  force: boolean,
): { relPath: string; ok: boolean; backupPath?: string; reason?: string }[] {
  const def = getManagedFile(key);
  if (!def) throw new Error(`Unknown managed file "${key}"`);
  const proposedMap = def.buildProposed(values);

  return def.relPaths.map((relPath) => {
    const absolute = repoPath(relPath);
    const existsNow = fs.existsSync(absolute);
    const currentNow = existsNow ? fs.readFileSync(absolute, "utf8") : "";
    const confirmedHash = confirmedHashes[relPath];

    if (!force && confirmedHash && hashContent(currentNow) !== confirmedHash) {
      return {
        relPath,
        ok: false,
        reason: "File changed on disk since the diff was shown — re-open the diff and try again.",
      };
    }

    let backupPath: string | undefined;
    if (existsNow) {
      backupPath = `${absolute}.bak-${Date.now()}`;
      fs.copyFileSync(absolute, backupPath);
    }

    fs.mkdirSync(path.dirname(absolute), { recursive: true });
    fs.writeFileSync(absolute, proposedMap[relPath] ?? "", "utf8");
    return { relPath, ok: true, backupPath };
  });
}
