// ── .env (personal — DEV_EMAIL / AWS_* / START_MODE / JIRA_*) ──────────────

function parseEnvFile(content: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of content.split("\n")) {
    const m = /^([A-Z_][A-Z0-9_]*)=(.*)$/.exec(line);
    if (m) out[m[1]!] = m[2] ?? "";
  }
  return out;
}

function upsertEnvKeys(content: string, updates: Record<string, string>): string {
  const lines = content.split("\n");
  const seen = new Set<string>();
  const next = lines.map((line) => {
    const m = /^([A-Z_][A-Z0-9_]*)=/.exec(line);
    if (m && Object.prototype.hasOwnProperty.call(updates, m[1]!)) {
      seen.add(m[1]!);
      return `${m[1]}=${updates[m[1]!]}`;
    }
    return line;
  });
  const missing = Object.entries(updates).filter(([k]) => !seen.has(k));
  if (missing.length > 0) {
    if (next[next.length - 1]?.trim() !== "") next.push("");
    next.push("# ── Added by onboarding-ui ──");
    for (const [k, v] of missing) next.push(`${k}=${v}`);
  }
  return next.join("\n").replace(/\n{3,}/g, "\n\n");
}

